// Regenerates the word assets from SCOWL (npm `wordlist-english`, devDependency).
//   node src/kits/word/build-dict.mjs
// Outputs (both committed, so the build doesn't need to run this):
//   dict.txt  – validation dictionary, lowercase a–z, 3–8 letters, SCOWL levels 10–60,
//               front-coded: each entry is "<shared-prefix length digit><suffix>".
//               Loaded lazily (dynamic import) so the main bundle stays small.
//   common.ts – common words (SCOWL levels 10–20), 3–6 letters, bundled synchronously
//               so puzzles can be generated without waiting for the dictionary.
// SCOWL copyright 2000-2016 Kevin Atkinson; permissive licence, see node_modules/wordlist-english/Copyright.
// Also regenerates the French assets (dict-fr.txt, common-fr.ts) via build-dict-fr.mjs.
import { createRequire } from 'node:module';
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const here = dirname(fileURLToPath(import.meta.url));
const load = (levels) => {
  const s = new Set();
  for (const l of levels)
    for (const v of ['english', 'american']) {
      for (const w of require(`wordlist-english/${v}-words-${l}.json`)) if (/^[a-z]{3,8}$/.test(w)) s.add(w);
    }
  return s;
};

